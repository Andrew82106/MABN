"""Prefix-only early warning evaluation for the A2A adapter.

Only events before the first explicit violation marker are visible.  The final
violation outcome is retained as an outcome label, never as an input feature.
This is still a benchmark sanity check because the outcome is generated by the
same harness, but it tests whether a monitor can warn before the terminal event.
"""
import json, math
from collections import defaultdict
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
EP=ROOT / 'data/processed/mas_adapter/a2asecbench/episodes.jsonl'; EV=ROOT / 'data/processed/mas_adapter/a2asecbench/events.jsonl'
OUT=ROOT / 'experiments/a2asecbench/runs/a2a_early_warning_v1'; OUT.mkdir(parents=True,exist_ok=True)
DANGER={'uri_dereference','artifact_executed','artifact_execution_error','cycle_detected','max_depth_exceeded','task_store_pressure'}
eps={json.loads(x)['episode_id']:json.loads(x) for x in EP.read_text(encoding='utf8').splitlines() if x.strip()}
events=defaultdict(list)
for x in EV.read_text(encoding='utf8').splitlines():
 if x.strip():
  e=json.loads(x); events[e['episode_id']].append(e)
def row(ep, frac):
 es=events.get(ep['episode_id'],[]); n=len(es); cut=max(0,min(n,int(math.ceil(n*frac))))
 pre=es[:cut]; agents={e.get('agent_id') for e in pre if e.get('agent_id')}; edges={(e.get('message_source'),e.get('message_target')) for e in pre if e.get('message_source') and e.get('message_target') and e.get('message_source')!=e.get('message_target')}
 types=[e.get('event_type','') for e in pre]
 return {'y':int(bool(ep['observed_violation'])),'case':ep['case_id'],'x':{'events':min(cut/20,1),'agents':min(len(agents)/5,1),'edges':min(len(edges)/5,1),'messages':min(sum(t=='a2a_message_sent' for t in types)/10,1),'delegations':min(sum(t=='delegation_edge' for t in types)/5,1),'tasks':min(sum(t=='task_created' for t in types)/10,1),'danger_prefix':int(any(t in DANGER for t in types))}}
def fit(train, keys):
 prior=(sum(r['y'] for r in train)+1)/(len(train)+2); c={}
 for k in keys:
  c[k]={}
  for y in (0,1):
   g=[r for r in train if r['y']==y]; c[k][y]=(sum(r['x'][k] > 0 for r in g)+1)/(len(g)+2)
 return prior,c
def pred(m,r,keys):
 prior,c=m; ls=[]
 for y in (0,1):
  z=math.log(prior if y else 1-prior)
  for k in keys:
   q=c[k][y]; z+=math.log(q if r['x'][k]>0 else 1-q)
  ls.append(z)
 return 1/(1+math.exp(max(-30,min(30,ls[0]-ls[1]))))
def met(rs,ss):
 ys=[r['y'] for r in rs]; ps=[s>=.5 for s in ss]; tp=sum(a and b for a,b in zip(ps,ys)); fp=sum(a and not b for a,b in zip(ps,ys)); fn=sum((not a) and b for a,b in zip(ps,ys)); tn=sum((not a) and (not b) for a,b in zip(ps,ys)); p=tp/(tp+fp) if tp+fp else 0; recall=tp/(tp+fn) if tp+fn else 0; f=2*p*recall/(p+recall) if p+recall else 0; return {'tp':tp,'fp':fp,'fn':fn,'tn':tn,'precision':p,'recall':recall,'specificity':tn/(tn+fp) if tn+fp else 0,'f1':f}
base=[e for e in eps.values() if e['observed_violation'] is not None]
cases=sorted({e['case_id'] for e in base}); train_cases=set(cases[:max(1,int(len(cases)*.7))]); result={}
for frac in (.25,.5,.75):
 rs=[row(e,frac) for e in base]; tr=[r for r in rs if r['case'] in train_cases]; te=[r for r in rs if r['case'] not in train_cases]; keys=['events','agents','edges','messages','delegations','tasks']
 m=fit(tr,keys); result[str(frac)]={'single_agent_nb':met(te,[pred(m,r,['events','messages','tasks']) for r in te]),'dynamic_bn':met(te,[pred(m,r,keys) for r in te]),'any_event':met(te,[float(r['x']['events']>0) for r in te]),'n_test':len(te)}
payload={'dataset':'A2ASecBench canonical adapter','evaluated':len(base),'excluded_null':len(eps)-len(base),'split':'case-level 70/30','danger_markers_excluded_from_prefix_input':sorted(DANGER),'fractions':result,'caveat':'Outcome is harness-derived; prefix evaluation is early-warning sanity, not independent security ground truth.'}
(OUT/'metrics.json').write_text(json.dumps(payload,ensure_ascii=False,indent=2),encoding='utf8')
lines=['# A2A prefix early-warning evaluation v1','','只使用终止违规标记之前的运行事件前缀；最终违规结果只作为 outcome label。','']
for k,d in result.items():
 lines.append('- prefix %s: %s' % (k, ', '.join('%s F1=%.3f, recall=%.3f, specificity=%.3f' % (n,v['f1'],v['recall'],v['specificity']) for n,v in d.items() if isinstance(v,dict) and 'f1' in v)))
lines += ['','这是提前预警 sanity check，仍受 benchmark outcome 定义影响，不能当作无泄漏部署性能。']
(OUT/'REPORT.md').write_text('\n'.join(lines)+'\n',encoding='utf8')
print(json.dumps(payload,ensure_ascii=False,indent=2))
